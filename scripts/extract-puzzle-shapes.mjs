import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const DEFAULT_SOURCE = ".artifacts/puzzle-research/jigsawmake-4x3";
const DEFAULT_OUTPUT = "src/client/assets/puzzles/sunset-grid-12-paths.js";
const DEFAULT_ARTWORK_OUTPUT = "src/client/assets/puzzles/sunset-grid-12-artwork.jpg";

const sourceDirectory = resolve(process.argv[2] ?? DEFAULT_SOURCE);
const outputPath = resolve(process.argv[3] ?? DEFAULT_OUTPUT);
const artworkOutputPath = resolve(process.argv[4] ?? DEFAULT_ARTWORK_OUTPUT);
const sourceFiles = readdirSync(sourceDirectory)
  .filter((name) => /^piece_r\d+_c\d+\.svg$/i.test(name))
  .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }));

if (!sourceFiles.length) {
  throw new Error(`No piece_r*_c*.svg files found in ${sourceDirectory}.`);
}

let artworkBase64 = "";
const paths = sourceFiles.map((name) => {
  const source = readFileSync(resolve(sourceDirectory, name), "utf8");
  const path = source.match(
    /<clipPath\b[^>]*>[\s\S]*?<path\b[^>]*\bd="([^"]+)"[^>]*>/i,
  )?.[1]?.replace(/\s+/g, " ").trim();
  if (!path || !/[zZ]$/.test(path)) {
    throw new Error(`${name} does not contain a closed clip-path contour.`);
  }
  const embeddedArtwork = source.match(
    /<image\b[^>]*\bhref="data:image\/jpeg;base64,([^"]+)"/i,
  )?.[1];
  if (!embeddedArtwork) {
    throw new Error(`${name} does not contain the expected embedded JPEG artwork.`);
  }
  if (artworkBase64 && embeddedArtwork !== artworkBase64) {
    throw new Error(`${name} embeds different artwork from the other pieces.`);
  }
  artworkBase64 = embeddedArtwork;
  return path;
});

const pieces = paths.map((path) => {
  const coordinates = [...path.matchAll(/-?\d+(?:\.\d+)?/g)]
    .map((match) => Number(match[0]));
  const xValues = coordinates.filter((_, index) => index % 2 === 0);
  const yValues = coordinates.filter((_, index) => index % 2 === 1);
  const x = Math.min(...xValues);
  const y = Math.min(...yValues);
  return {
    path,
    bounds: {
      x,
      y,
      width: Math.max(...xValues) - x,
      height: Math.max(...yValues) - y,
    },
  };
});

const output = `// Generated by scripts/extract-puzzle-shapes.mjs.
// Source: user-exported JigsawMake "Pieces SVG (ZIP)", 4 x 3 layout.
// Closed contours keep their original global-coordinate bounds; one shared artwork file is emitted.

export const SUNSET_GRID_12_PIECES = Object.freeze(
  ${JSON.stringify(pieces, null, 2)}.map((piece) => Object.freeze({
    ...piece,
    bounds: Object.freeze(piece.bounds),
  })),
);
export const SUNSET_GRID_12_PATHS = Object.freeze(
  SUNSET_GRID_12_PIECES.map(({ path }) => path),
);
`;

writeFileSync(outputPath, output, "utf8");
writeFileSync(artworkOutputPath, Buffer.from(artworkBase64, "base64"));
console.log(
  `Extracted ${pieces.length} closed contours with bounds and one shared JPEG artwork.`,
);
